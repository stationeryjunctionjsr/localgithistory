import asyncio
from datetime import datetime
from typing import TYPE_CHECKING, List, Optional, Union
from app.models.schemas import ProductReviewResponse
from sqlalchemy import text

from app.db.storage_factory import get_storage
from app.config.database import get_async_session_factory
from app.utils.logger import logger

if TYPE_CHECKING:
    from app.models.daos import ProductReviewsInternalCreate, ProductReviewsInternalUpdate
    


class ProductReviewRepository:
    def __init__(self) -> None:
        self._storage = None
        self._initialized = False

    @property
    def storage(self):
        if self._storage is None:
            self._storage = get_storage("productReviews")
        return self._storage

    async def ensure_table_exists(self) -> None:
        if self._initialized:
            return
        self._initialized = True
        return
        from app.config.settings import settings

        table_name_upper = f"SJ_PRODUCT_REVIEWS".upper()
        table_name_lower = f"sj_product_reviews".lower()
        constraint_name_lower = f"uq_prod_review_external".lower()

        factory = get_async_session_factory()
        if not factory:
            return
        async with factory() as session:
            try:
                result = await session.execute(
                    text("SELECT table_name FROM user_tables WHERE table_name = :tname"), {"tname": table_name_upper}
                )
                row = result.fetchone()
                if not row:
                    logger.info("Table %s does not exist. Creating it...", table_name_upper)
                    await session.execute(
                        text(f"""
                        CREATE TABLE {table_name_lower} (
                          id           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
                          doc          CLOB,
                          created_at   TIMESTAMP,
                          updated_at   TIMESTAMP
                        )
                        """)
                    )
                    await session.commit()
                    logger.info("Table %s created successfully.", table_name_upper)
                self._initialized = True
            except Exception as e:
                logger.error("Error ensuring %s exists: %s", table_name_upper, str(e))

    async def findAll(
        self,
        product_id: Optional[Union[int, str]] = None,
        user_id: Optional[str] = None,
        rating: Optional[int] = None,
        status: Optional[str] = None,
    ) -> List[ProductReviewResponse]:
        await self.ensure_table_exists()
        pid = None
        if product_id is not None:
            try:
                pid = int(str(product_id).replace("PDT-", ""))
            except (ValueError, TypeError):
                pid = None
        return await self.storage.findAll(product_id=pid, user_id=user_id, rating=rating, status=status)

    async def find_approved_by_product(self, product_id: Union[int, str]) -> List[ProductReviewResponse]:
        await self.ensure_table_exists()
        try:
            pid = int(str(product_id).replace("PDT-", ""))
        except (ValueError, TypeError):
            pid = None
        return await self.storage.findAll(product_id=pid, status="approved")

    async def findById(self, id: int) -> Optional[ProductReviewResponse]:
        await self.ensure_table_exists()
        return await self.storage.findById(id)

    async def create(self, data: 'ProductReviewsInternalCreate') -> Optional[ProductReviewResponse]:
        await self.ensure_table_exists()
        return await self.storage.create(data)

    async def update(self, id: int, update_data: 'ProductReviewsInternalUpdate') -> Optional[ProductReviewResponse]:
        await self.ensure_table_exists()
        return await self.storage.update(id, update_data)

    async def delete(self, id: int) -> bool:
        await self.ensure_table_exists()
        return await self.storage.delete(id)


product_review_repository = ProductReviewRepository()
