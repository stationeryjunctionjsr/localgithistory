-- Oracle schema for Stationery Junction (Always Free / compatible)
-- Run as application user. Uses IDENTITY PKs and external_id for API compatibility.
-- Table prefix sj_ (Stationery Junction) avoids reserved words (USER, ORDER, etc.).

-- ========== USERS ==========
CREATE TABLE sj_users (
  user_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  external_id  VARCHAR2(32) NOT NULL,
  user_id_formatted VARCHAR2(32),
  name         VARCHAR2(255),
  email        VARCHAR2(255),
  password_hash VARCHAR2(255),
  role         VARCHAR2(32),
  phone        VARCHAR2(64),
  company_name VARCHAR2(255),
  address      CLOB,
  saved_addresses CLOB,
  is_active    NUMBER(1) DEFAULT 1,
  approval_status VARCHAR2(32),
  is_deactivated NUMBER(1) DEFAULT 0,
  credit_limit NUMBER(18,2) DEFAULT 0,
  credit_used  NUMBER(18,2) DEFAULT 0,
  payment_terms VARCHAR2(32),
  assigned_salesperson VARCHAR2(32),
  created_at   TIMESTAMP,
  updated_at   TIMESTAMP,
  CONSTRAINT uq_sj_users_external UNIQUE (external_id)
);
CREATE INDEX ix_sj_users_email ON sj_users (email);
CREATE INDEX ix_sj_users_phone ON sj_users (phone);
CREATE INDEX ix_sj_users_role ON sj_users (role);

-- ========== CATEGORIES ==========
