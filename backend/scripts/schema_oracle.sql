CREATE INDEX ix_sj_products_category ON sj_products (category);

-- ========== ORDERS (user_id FK) ==========
CREATE TABLE sj_orders (
  id           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  external_id  VARCHAR2(32) NOT NULL,
  user_id      NUMBER NOT NULL,
  order_number VARCHAR2(64) NOT NULL,
  status       VARCHAR2(32),
  total        NUMBER(18,2),
  subtotal     NUMBER(18,2),
  tax          NUMBER(18,2) DEFAULT 0,
  shipping     NUMBER(18,2) DEFAULT 0,
  discount     NUMBER(18,2) DEFAULT 0,
  order_type   VARCHAR2(32),
  payment_status VARCHAR2(32),
  payment_method VARCHAR2(32),
  upi_payment_screenshot CLOB,
  shipping_address CLOB,
  billing_address CLOB,
  notes        VARCHAR2(4000),
  printed_bill NUMBER(1) DEFAULT 0,
  assigned_valet VARCHAR2(32),
  shipped_at   TIMESTAMP,
  delivered_at TIMESTAMP,
  cod_payment_received NUMBER(1) DEFAULT 0,
  cod_payment_received_at TIMESTAMP,
  decline_reason VARCHAR2(4000),
  cancelled_at TIMESTAMP,
  cancelled_by VARCHAR2(32),
  turnaround_hours NUMBER(10,2),
  created_at   TIMESTAMP,
  updated_at   TIMESTAMP,
  CONSTRAINT uq_sj_orders_external UNIQUE (external_id),
  CONSTRAINT fk_sj_orders_user FOREIGN KEY (user_id) REFERENCES sj_users (user_id)
);
CREATE INDEX ix_sj_orders_user ON sj_orders (user_id);
CREATE INDEX ix_sj_orders_status ON sj_orders (status);
CREATE INDEX ix_sj_orders_created ON sj_orders (created_at);
CREATE UNIQUE INDEX ix_sj_orders_order_number ON sj_orders (order_number);

-- ========== ORDER ITEMS ==========
CREATE TABLE sj_order_items (
  id           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  order_id     NUMBER NOT NULL,
  product_id   NUMBER NOT NULL,
  quantity     NUMBER NOT NULL,
  price        NUMBER(18,2) NOT NULL,
  CONSTRAINT fk_oi_order FOREIGN KEY (order_id) REFERENCES sj_orders (id) ON DELETE CASCADE,
  CONSTRAINT fk_oi_product FOREIGN KEY (product_id) REFERENCES sj_products (id)
);
CREATE INDEX ix_sj_order_items_order ON sj_order_items (order_id);
CREATE INDEX ix_sj_order_items_product ON sj_order_items (product_id);

